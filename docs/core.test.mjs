import assert from "node:assert/strict";
import {maskFor,redactRGBA,crc32,zipStore} from "./core.mjs";
const m=maskFor(5,4,[{kind:"rect",a:[1,1],b:[3,2]}]);
assert.equal(m.reduce((a,b)=>a+b,0),6);
const rgba=new Uint8Array(80).fill(77);assert.equal(redactRGBA(rgba,m,0),6);
assert.deepEqual(Array.from(rgba.slice(24,28)),[0,0,0,255]);assert.equal(rgba[0],77);
const er=maskFor(5,5,[{kind:"rect",a:[0,0],b:[4,4]},{kind:"erase",radius:1,points:[[2,2]]}]);assert.equal(er[12],0);assert.equal(er[0],1);
const br=maskFor(12,5,[{kind:"brush",radius:1,points:[[1,2],[10,2]]}]);assert.ok(br.slice(25,35).every(x=>x===1));
assert.equal(crc32(Uint8Array.from([49,50,51,52,53,54,55,56,57])),0xcbf43926);
const chunks=zipStore([{name:"0001_redacted.png",data:Uint8Array.of(1,2,3)}]);assert.equal(new DataView(chunks[0].buffer).getUint32(0,true),0x04034b50);assert.equal(new DataView(chunks.at(-1).buffer).getUint16(10,true),1);
assert.throws(()=>zipStore([{name:"../private.png",data:Uint8Array.of(1)}]));
console.log("Core checks passed");
