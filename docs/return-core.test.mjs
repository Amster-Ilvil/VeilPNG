import assert from 'node:assert/strict';
import {sourceHash,maskRecord,loadMaskRecord,restoreRGBA} from './return-core.mjs';
const hash=await sourceHash(new Blob(['abc']));
assert.equal(hash,'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
const ops=[{kind:'rect',a:[0,0],b:[1,0]},{kind:'erase',radius:1,points:[[0,0]]}];
const rec=maskRecord(2,2,hash,ops,0),raw=JSON.stringify(rec);
assert.deepEqual(loadMaskRecord(raw,2,2,hash),rec);
assert.throws(()=>loadMaskRecord(raw,2,2,'a'.repeat(64)));
assert.throws(()=>loadMaskRecord(raw,3,2,hash));
assert.throws(()=>loadMaskRecord('{',2,2,hash));
assert.throws(()=>maskRecord(2,2,hash,[{kind:'rect',a:[-1,0],b:[1,0]}],0));
assert.throws(()=>maskRecord(2,2,hash,[{kind:'brush',radius:999,points:[[0,0]]}],0));
assert.throws(()=>maskRecord(2,2,hash,[{kind:'weird'}],0));
const a=Uint8Array.from([1,2,3,4,5,6,7,8]),b=Uint8Array.from([9,10,11,12,13,14,15,16]);
assert.equal(restoreRGBA(a,b,Uint8Array.of(1,0)),1);
assert.deepEqual([...b],[1,2,3,4,13,14,15,16]);
assert.throws(()=>restoreRGBA(a,b,Uint8Array.of(0,0)));
assert.throws(()=>restoreRGBA(a,b,Uint8Array.of(1)));
console.log('12 return-core checks passed');
