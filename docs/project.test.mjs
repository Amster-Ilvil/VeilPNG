import assert from 'node:assert/strict';
import {projectRecord,matchProject,returnIndex,validRole} from './project.mjs';
const p=(name,hash,role)=>({file:{name},hash:hash.repeat(64),width:4,height:4,role,shade:0,ops:[{kind:'rect',a:[0,0],b:[1,1]}]});
const a=p('a.png','a','中'),b=p('b.png','b','日'),r=projectRecord([a,b]);
assert.equal(r.pages.length,2);
assert.equal(matchProject(r,[b,a])[0].file.name,'a.png');
assert.equal(matchProject(r,[b,a])[1].role,'日');
assert.throws(()=>matchProject(r,[a,a]));
assert.throws(()=>matchProject(r,[a]));
assert.equal(returnIndex('0002_returned.jpg',2),1);
assert.equal(returnIndex('0001_redacted.png',2),0);
assert.throws(()=>returnIndex('gemini.png',2));
assert.throws(()=>returnIndex('0003_redacted.png',2));
assert.equal(validRole('unknown'),'其他');
console.log('10 project checks passed');
